/**
 * DACL CLI commands — manage declarative access control policies.
 * Subcommands: list, test, generate-rls, coverage
 */

import { existsSync, writeFileSync, mkdirSync } from "node:fs"
import { join } from "node:path"

export interface DaclCommandOptions {
  projectDir: string
  connectionString?: string
}

/**
 * List all defined DACL policies.
 */
export async function daclList(options: DaclCommandOptions): Promise<void> {
  const policiesPath = findPoliciesFile(options.projectDir)

  if (!policiesPath) {
    console.log("No policies file found.")
    console.log("Create a policies file at one of:")
    console.log("  - convex/policies.ts")
    console.log("  - src/policies.ts")
    console.log("  - policies.ts")
    console.log("")
    console.log("Example:")
    console.log('  import { allow, deny } from "@reactivebase/server"')
    console.log("")
    console.log("  export const policies = [")
    console.log('    allow("tasks", "read").roles("admin", "developer"),')
    console.log('    deny("tasks", "delete").describe("No deletes allowed"),')
    console.log("  ]")
    return
  }

  console.log(`Found policies at: ${policiesPath}`)
  console.log("")
  console.log("Defined policies:")
  console.log("  (Policies are loaded at runtime from your TypeScript file)")
  console.log("  Use `reactivebase dacl test` to validate them.")
}

/**
 * Run policy test cases.
 */
export async function daclTest(options: DaclCommandOptions): Promise<void> {
  const testPath = findPolicyTestFile(options.projectDir)

  if (!testPath) {
    console.log("No policy test file found.")
    console.log("Create a test file at one of:")
    console.log("  - convex/policies.test.ts")
    console.log("  - src/policies.test.ts")
    console.log("")
    console.log("Example:")
    console.log('  import { PolicyTestCase } from "@reactivebase/server"')
    console.log("")
    console.log("  export const testCases: PolicyTestCase[] = [")
    console.log('    { name: "admin can read", context: { ... }, expectedResult: true },')
    console.log("  ]")
    return
  }

  console.log(`Running policy tests from: ${testPath}`)
  console.log("Use vitest to run your policy tests directly:")
  console.log(`  npx vitest run ${testPath}`)
}

/**
 * Generate Postgres RLS SQL from DACL policies.
 */
export async function daclGenerateRls(options: DaclCommandOptions): Promise<void> {
  const policiesPath = findPoliciesFile(options.projectDir)

  if (!policiesPath) {
    console.log("Error: No policies file found.")
    return
  }

  const outputDir = join(options.projectDir, "migrations")
  mkdirSync(outputDir, { recursive: true })

  const timestamp = Date.now()
  const outputFile = join(outputDir, `${timestamp}_rls_policies.sql`)

  const content = `-- RLS Policies generated by ReactiveBase DACL
-- Generated at: ${new Date().toISOString()}
-- Source: ${policiesPath}
--
-- To apply: reactivebase migrate --apply
-- To customize: edit this file before applying
--
-- NOTE: This is a template. Actual RLS SQL is generated at runtime
-- from your TypeScript policy definitions using DaclEngine.generateRlsSQL().
--
-- Example usage in your server code:
--   import { DaclEngine, allow, deny } from "@reactivebase/server"
--   const engine = new DaclEngine()
--   engine.definePolicy(allow("tasks", "read").roles("admin"))
--   const sqlStatements = engine.generateRlsSQL()
--

-- Enable RLS on tables (uncomment and modify as needed):
-- ALTER TABLE "tasks" ENABLE ROW LEVEL SECURITY;
-- ALTER TABLE "users" ENABLE ROW LEVEL SECURITY;

-- Create policies (uncomment and modify as needed):
-- CREATE POLICY "allow_read_tasks" ON "tasks" FOR SELECT USING (true);
-- CREATE POLICY "allow_write_tasks" ON "tasks" FOR ALL USING (
--   current_setting('app.user_role') IN ('admin', 'editor')
-- );
`

  writeFileSync(outputFile, content, "utf-8")
  console.log(`Generated RLS migration: ${outputFile}`)
  console.log("")
  console.log("Next steps:")
  console.log("  1. Edit the migration to match your policies")
  console.log("  2. Run `reactivebase migrate --apply` to apply")
}

/**
 * Show policy coverage report.
 */
export async function daclCoverage(options: DaclCommandOptions): Promise<void> {
  const policiesPath = findPoliciesFile(options.projectDir)

  if (!policiesPath) {
    console.log("Error: No policies file found.")
    return
  }

  console.log("Policy Coverage Report")
  console.log("======================")
  console.log("")
  console.log("To generate a coverage report, use DaclEngine.getCoverage() in your code:")
  console.log("")
  console.log('  import { DaclEngine } from "@reactivebase/server"')
  console.log("  const engine = new DaclEngine()")
  console.log("  // ... define policies ...")
  console.log('  const report = engine.getCoverage(["tasks", "users"], ["read", "write", "delete"])')
  console.log("  console.log(`Coverage: ${report.coveragePercentage.toFixed(1)}%`)")
}

function findPoliciesFile(projectDir: string): string | null {
  const candidates = ["convex/policies.ts", "src/policies.ts", "policies.ts", "convex/access.ts", "src/access.ts"]
  for (const candidate of candidates) {
    const filePath = join(projectDir, candidate)
    if (existsSync(filePath)) return filePath
  }
  return null
}

function findPolicyTestFile(projectDir: string): string | null {
  const candidates = ["convex/policies.test.ts", "src/policies.test.ts", "policies.test.ts"]
  for (const candidate of candidates) {
    const filePath = join(projectDir, candidate)
    if (existsSync(filePath)) return filePath
  }
  return null
}
