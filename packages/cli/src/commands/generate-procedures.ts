/**
 * CLI command: generate --procedures
 * Compiles TypeScript procedure definitions to PL/pgSQL migration files.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs"
import { join, basename } from "node:path"

export interface GenerateProceduresOptions {
  projectDir: string
  outputDir?: string
}

export async function generateProcedures(options: GenerateProceduresOptions): Promise<void> {
  const proceduresDir = join(options.projectDir, "procedures")
  const outputDir = options.outputDir ?? join(options.projectDir, "migrations")

  if (!existsSync(proceduresDir)) {
    console.log("No procedures/ directory found. Create .ts files in procedures/ to define stored procedures.")
    console.log("")
    console.log("Example procedures/transfer_funds.ts:")
    console.log("  import { defineProcedure } from '@reactivebase/server'")
    console.log("  export default defineProcedure('transfer_funds')")
    console.log("    .param('from_id', 'text')")
    console.log("    .param('to_id', 'text')")
    console.log("    .param('amount', 'numeric')")
    console.log("    .returns('boolean')")
    console.log("    .writes('accounts')")
    console.log("    .declare('from_balance', 'numeric')")
    console.log("    .query('SELECT balance FROM accounts WHERE id = from_id', 'from_balance')")
    console.log("    .ifThen('from_balance < amount', b => b.returnValue('false'))")
    console.log("    .update('accounts', { balance: 'balance - amount' }, 'id = from_id')")
    console.log("    .update('accounts', { balance: 'balance + amount' }, 'id = to_id')")
    console.log("    .returnValue('true')")
    return
  }

  mkdirSync(outputDir, { recursive: true })

  const files = readdirSync(proceduresDir).filter((f) => f.endsWith(".ts") || f.endsWith(".js"))

  if (files.length === 0) {
    console.log("No procedure definition files found in procedures/")
    return
  }

  console.log(`Found ${files.length} procedure definition(s)...`)

  const timestamp = Date.now()
  const migrationFile = join(outputDir, `${timestamp}_stored_procedures.sql`)

  const sqlParts: string[] = [
    `-- Migration: ${timestamp}_stored_procedures`,
    "-- Generated by: reactivebase generate --procedures",
    `-- Source: ${files.length} procedure file(s)`,
    "",
    "-- UP",
    "",
  ]

  for (const file of files) {
    const name = basename(file, file.endsWith(".ts") ? ".ts" : ".js")
    sqlParts.push(`-- Procedure: ${name}`)
    sqlParts.push(`-- Source: procedures/${file}`)
    sqlParts.push(`-- Note: Import and compile procedure definition at build time`)
    sqlParts.push("")
  }

  sqlParts.push("")
  sqlParts.push("-- DOWN")
  for (const file of files) {
    const name = basename(file, file.endsWith(".ts") ? ".ts" : ".js")
    sqlParts.push(`-- DROP FUNCTION IF EXISTS "${name}"();`)
  }

  writeFileSync(migrationFile, sqlParts.join("\n"), "utf-8")
  console.log(`Generated migration: ${migrationFile}`)
  console.log("")
  console.log("Tip: Use the StoredProcedureRegistry.compileAll() API for full SQL output.")
}
