/**
 * Type generation - generates TypeScript types from schema definitions.
 * Produces api.ts, dataModel.ts for end-to-end type safety.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync } from "node:fs"
import { join, resolve, extname } from "node:path"

export interface GeneratedFile {
  path: string
  content: string
}

/**
 * Generate TypeScript types from schema and server function files.
 */
export function generateTypes(projectDir: string): GeneratedFile[] {
  const outputDir = join(projectDir, "_generated")
  const files: GeneratedFile[] = []

  // Scan for schema file
  const schemaContent = findSchemaFile(projectDir)
  const functions = findFunctionFiles(projectDir)

  // Generate data model types
  files.push({
    path: join(outputDir, "dataModel.ts"),
    content: generateDataModel(schemaContent),
  })

  // Generate API object with typed function references
  files.push({
    path: join(outputDir, "api.ts"),
    content: generateApiFile(functions),
  })

  // Generate server context types
  files.push({
    path: join(outputDir, "server.ts"),
    content: generateServerTypes(),
  })

  return files
}

/**
 * Write generated files to disk.
 */
export function writeGeneratedFiles(projectDir: string): void {
  const files = generateTypes(projectDir)
  const outputDir = join(projectDir, "_generated")

  mkdirSync(outputDir, { recursive: true })

  for (const file of files) {
    writeFileSync(file.path, file.content, "utf-8")
  }

  console.log(`Generated ${files.length} type files in ${outputDir}`)
}

function findSchemaFile(projectDir: string): string | null {
  const candidates = ["schema.ts", "schema.tsx", "convex/schema.ts", "src/schema.ts"]

  for (const candidate of candidates) {
    const filePath = join(projectDir, candidate)
    if (existsSync(filePath)) {
      return readFileSync(filePath, "utf-8")
    }
  }

  return null
}

interface FunctionInfo {
  name: string
  namespace: string
  type: "query" | "mutation" | "action"
}

function findFunctionFiles(projectDir: string): FunctionInfo[] {
  const functions: FunctionInfo[] = []
  const searchDirs = ["convex", "src/functions", "src", "."]

  for (const dir of searchDirs) {
    const fullDir = join(projectDir, dir)
    if (!existsSync(fullDir)) continue

    try {
      const entries = readdirSync(fullDir)
      for (const entry of entries) {
        const entryPath = join(fullDir, entry)
        const stat = statSync(entryPath)

        if (stat.isFile() && (entry.endsWith(".ts") || entry.endsWith(".tsx"))) {
          if (entry === "schema.ts" || entry === "schema.tsx") continue
          if (entry.startsWith("_")) continue

          const content = readFileSync(entryPath, "utf-8")
          const namespace = entry.replace(extname(entry), "")

          // Detect exported queries, mutations, actions
          const exportRegex = /export\s+const\s+(\w+)\s*=\s*(query|mutation|action)\(/g
          let match

          while ((match = exportRegex.exec(content)) !== null) {
            functions.push({
              name: match[1],
              namespace,
              type: match[2] as "query" | "mutation" | "action",
            })
          }
        }
      }
    } catch {
      // Directory doesn't exist or can't be read
    }
  }

  return functions
}

function generateDataModel(_schemaContent: string | null): string {
  return `/**
 * Generated by ReactiveBase - do not edit manually.
 * This file contains TypeScript types derived from your schema definition.
 */

/* eslint-disable */

import type { InferSchemaTypes } from "@reactivebase/server"

/**
 * The data model types for your ReactiveBase application.
 * These types are generated from your schema.ts file.
 *
 * To update: run \`npx reactivebase generate\`
 */
export type DataModel = Record<string, Record<string, unknown>>

/**
 * A document ID type for a specific table.
 */
export type Id<TableName extends string> = string & { __tableName: TableName }
`
}

function generateApiFile(functions: FunctionInfo[]): string {
  const namespaces = new Map<string, FunctionInfo[]>()

  for (const fn of functions) {
    if (!namespaces.has(fn.namespace)) {
      namespaces.set(fn.namespace, [])
    }
    namespaces.get(fn.namespace)!.push(fn)
  }

  let content = `/**
 * Generated by ReactiveBase - do not edit manually.
 * This file provides typed references to your server functions.
 */

/* eslint-disable */

export interface FunctionReference {
  _name: string
  _type: "query" | "mutation" | "action"
}

function ref(name: string, type: "query" | "mutation" | "action"): FunctionReference {
  return { _name: name, _type: type }
}

`

  if (namespaces.size === 0) {
    content += `/**
 * No server functions found. Define queries, mutations, and actions
 * in your project to see them appear here.
 *
 * Example:
 *   export const listTasks = query(async (ctx) => { ... })
 */
export const api = {} as const
`
  } else {
    content += `export const api = {\n`

    for (const [namespace, fns] of namespaces) {
      content += `  ${namespace}: {\n`
      for (const fn of fns) {
        content += `    ${fn.name}: ref("${namespace}.${fn.name}", "${fn.type}"),\n`
      }
      content += `  },\n`
    }

    content += `} as const\n`
  }

  return content
}

function generateServerTypes(): string {
  return `/**
 * Generated by ReactiveBase - do not edit manually.
 * This file provides typed context objects for server functions.
 */

/* eslint-disable */

export type { FunctionContext, SchedulerContext, LogContext } from "@reactivebase/server"
`
}
