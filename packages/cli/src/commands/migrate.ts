/**
 * Migration CLI commands - generate, apply, status, rollback, preview.
 */

import { writeFileSync, mkdirSync, existsSync, readdirSync, readFileSync } from "node:fs"
import { join } from "node:path"

export interface MigrateCommandOptions {
  projectDir: string
  connectionString?: string
}

export async function migrateGenerate(options: MigrateCommandOptions): Promise<void> {
  const migrationsDir = join(options.projectDir, "migrations")
  mkdirSync(migrationsDir, { recursive: true })

  const schemaPath = findSchemaPath(options.projectDir)
  if (!schemaPath) {
    console.error("Error: No schema file found. Create a schema.ts file.")
    process.exit(1)
  }

  console.log(`Generating migration from ${schemaPath}...`)

  const timestamp = Date.now()
  const version = String(timestamp)
  const migrationFile = join(migrationsDir, `${version}_migration.sql`)

  // Try to generate actual diff SQL if schema module is available
  let content: string
  try {
    const { generateMigrationSQL } = (await import("@reactivebase/server/schema" as string)) as {
      generateMigrationSQL: (schema: unknown) => string
    }

    // Read schema file to extract table definitions
    const schemaSource = readFileSync(schemaPath, "utf-8")

    // Extract table names from schema for a useful migration template
    const tableNames: string[] = []
    const tableRegex = /(\w+):\s*defineTable\s*\(/g
    let match: RegExpExecArray | null
    while ((match = tableRegex.exec(schemaSource)) !== null) {
      tableNames.push(match[1])
    }

    if (tableNames.length > 0) {
      content = `-- Migration: ${version}\n-- Generated by ReactiveBase CLI\n-- Tables detected: ${tableNames.join(", ")}\n\n-- UP\n`
      content += `-- Schema changes go here. Detected tables:\n`
      for (const table of tableNames) {
        content += `-- CREATE TABLE IF NOT EXISTS "${table}" (...);\n`
      }
      content += `\n-- DOWN\n-- Rollback SQL here.\n`
    } else {
      content = generateMigrationSQL({})
    }
  } catch {
    content = `-- Migration: ${version}\n-- Generated by ReactiveBase CLI\n\n-- UP\n-- Add your schema changes here.\n\n-- DOWN\n-- Add rollback SQL here.\n`
  }

  writeFileSync(migrationFile, content, "utf-8")
  console.log(`Created migration: ${migrationFile}`)
}

export async function migrateApply(options: MigrateCommandOptions): Promise<void> {
  const migrationsDir = join(options.projectDir, "migrations")
  if (!existsSync(migrationsDir)) {
    console.log("No migrations directory found. Run `reactivebase migrate --generate` first.")
    return
  }

  const files = readdirSync(migrationsDir)
    .filter((f) => f.endsWith(".sql"))
    .sort()

  if (files.length === 0) {
    console.log("No pending migrations.")
    return
  }

  const connectionString = options.connectionString ?? process.env.DATABASE_URL
  if (!connectionString) {
    console.error("Error: DATABASE_URL environment variable is required.")
    console.error("  Set it in your .env file or pass --connection-string.\n")
    process.exit(1)
  }

  console.log(`Found ${files.length} migration(s) to apply.\n`)

  // Connect to Postgres
  const { default: pg } = (await import("pg" as string)) as {
    default: {
      Pool: new (config: { connectionString: string }) => PgPool
    }
  }

  const pool = new pg.Pool({ connectionString })

  try {
    // Create migrations tracking table if it doesn't exist
    await pool.query(`
      CREATE TABLE IF NOT EXISTS _reactivebase_migrations (
        version TEXT PRIMARY KEY,
        filename TEXT NOT NULL,
        applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        checksum TEXT
      )
    `)

    // Get already-applied migrations
    const applied = await pool.query(`SELECT version FROM _reactivebase_migrations ORDER BY version`)
    const appliedVersions = new Set(applied.rows.map((r: Record<string, unknown>) => r.version as string))

    let appliedCount = 0
    let skippedCount = 0

    for (const file of files) {
      const version = file.split("_")[0]

      if (appliedVersions.has(version)) {
        skippedCount++
        continue
      }

      const filePath = join(migrationsDir, file)
      const sql = readFileSync(filePath, "utf-8")

      // Extract UP section (before -- DOWN)
      const upSql = extractUpSection(sql)

      if (!upSql.trim()) {
        console.log(`  ⚠ ${file}: empty migration, skipping`)
        skippedCount++
        continue
      }

      console.log(`  ▸ Applying: ${file}`)

      try {
        await pool.query("BEGIN")
        await pool.query(upSql)

        // Record the migration
        const checksum = simpleHash(sql)
        await pool.query(`INSERT INTO _reactivebase_migrations (version, filename, checksum) VALUES ($1, $2, $3)`, [
          version,
          file,
          checksum,
        ])

        await pool.query("COMMIT")
        console.log(`    ✓ Applied successfully`)
        appliedCount++
      } catch (error: unknown) {
        await pool.query("ROLLBACK").catch(() => {})
        console.error(`    ✗ Failed: ${error instanceof Error ? error.message : error}`)
        console.error(`    Rolling back. Fix the migration and retry.`)
        process.exit(1)
      }
    }

    if (appliedCount > 0 || skippedCount > 0) {
      console.log(`\n✓ Migrations complete: ${appliedCount} applied, ${skippedCount} skipped (already applied)`)
    } else {
      console.log("No pending migrations.")
    }
  } finally {
    await pool.end()
  }
}

export async function migrateStatus(options: MigrateCommandOptions): Promise<void> {
  const migrationsDir = join(options.projectDir, "migrations")
  if (!existsSync(migrationsDir)) {
    console.log("No migrations directory found.")
    return
  }

  const files = readdirSync(migrationsDir)
    .filter((f) => f.endsWith(".sql"))
    .sort()

  if (files.length === 0) {
    console.log("No migration files found.")
    return
  }

  const connectionString = options.connectionString ?? process.env.DATABASE_URL

  // If no DB connection, just list files
  if (!connectionString) {
    console.log("Migration files (no DB connection to check status):\n")
    for (const file of files) {
      console.log(`  📄 ${file}`)
    }
    console.log("\nSet DATABASE_URL to see applied/pending status.")
    return
  }

  // Connect and check status
  try {
    const { default: pg } = (await import("pg" as string)) as {
      default: { Pool: new (config: { connectionString: string }) => PgPool }
    }
    const pool = new pg.Pool({ connectionString })

    try {
      await pool.query(`
        CREATE TABLE IF NOT EXISTS _reactivebase_migrations (
          version TEXT PRIMARY KEY,
          filename TEXT NOT NULL,
          applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
          checksum TEXT
        )
      `)

      const applied = await pool.query(`SELECT version, applied_at FROM _reactivebase_migrations ORDER BY version`)
      const appliedMap = new Map<string, string>()
      for (const row of applied.rows as Array<Record<string, unknown>>) {
        appliedMap.set(row.version as string, new Date(row.applied_at as string).toISOString())
      }

      console.log("Migration status:\n")
      for (const file of files) {
        const version = file.split("_")[0]
        const appliedAt = appliedMap.get(version)
        if (appliedAt) {
          console.log(`  ✅ ${file}  (applied ${appliedAt})`)
        } else {
          console.log(`  ⏳ ${file}  (pending)`)
        }
      }
    } finally {
      await pool.end()
    }
  } catch {
    console.log("Migration files (could not connect to DB):\n")
    for (const file of files) {
      console.log(`  📄 ${file}`)
    }
  }
}

function findSchemaPath(projectDir: string): string | null {
  const candidates = ["schema.ts", "convex/schema.ts", "src/schema.ts"]
  for (const candidate of candidates) {
    const filePath = join(projectDir, candidate)
    if (existsSync(filePath)) return filePath
  }
  return null
}

export async function migratePreview(options: MigrateCommandOptions & { usePglite?: boolean }): Promise<void> {
  const migrationsDir = join(options.projectDir, "migrations")
  if (!existsSync(migrationsDir)) {
    console.log("No migrations directory found. Run `reactivebase migrate --generate` first.")
    return
  }

  const files = readdirSync(migrationsDir)
    .filter((f) => f.endsWith(".sql"))
    .sort()

  if (files.length === 0) {
    console.log("No migration files found.")
    return
  }

  const { MigrationAnalyzer, runPGliteShadowPreview } = (await import(
    "@reactivebase/server/migrations/migration-analyzer" as string
  )) as {
    MigrationAnalyzer: new () => { analyze: (sql: string) => unknown; formatCLIDiff: (analysis: unknown) => string }
    runPGliteShadowPreview: (sql: string) => Promise<{ success: boolean; error?: string; durationMs: number }>
  }

  const analyzer = new MigrationAnalyzer()

  for (const file of files) {
    const filePath = join(migrationsDir, file)
    const sql = readFileSync(filePath, "utf-8")

    console.log(`\n📋 Previewing: ${file}`)
    console.log("─".repeat(60))

    const analysis = analyzer.analyze(sql)
    console.log(analyzer.formatCLIDiff(analysis))

    if (options.usePglite) {
      console.log("\n🔬 Running PGlite shadow execution...")
      const result = await runPGliteShadowPreview(sql)
      if (result.success) {
        console.log(`   ✅ Migration applies cleanly (${result.durationMs}ms)`)
      } else {
        console.log(`   ❌ Migration failed: ${result.error}`)
      }
    }
  }
}

// Helper: extract UP section from migration SQL (before -- DOWN marker)
export function extractUpSection(sql: string): string {
  const downMarker = /^--\s*DOWN\b/im
  const match = downMarker.exec(sql)
  if (match) {
    return sql.substring(0, match.index)
  }
  return sql
}

// Simple string hash for migration checksums
export function simpleHash(str: string): string {
  let hash = 0
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i)
    hash = ((hash << 5) - hash + char) | 0
  }
  return Math.abs(hash).toString(36)
}

interface PgPool {
  query: (sql: string, params?: unknown[]) => Promise<{ rows: Record<string, unknown>[] }>
  end: () => Promise<void>
}
