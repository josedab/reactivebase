/**
 * Type-safe API code generator.
 * Scans function files (query/mutation/action exports) and generates
 * a typed `api` object with FunctionReference types for each function.
 *
 * Usage:
 *   import { api } from "./_generated/api"
 *   useQuery(api.tasks.listTasks, { userId: "u1" })
 */

import { readdir, readFile, writeFile, mkdir } from "node:fs/promises"
import { join, basename, extname, relative } from "node:path"
import { existsSync } from "node:fs"

export interface ScannedFunction {
  name: string
  module: string
  type: "query" | "mutation" | "action"
  exportName: string
}

/**
 * Scan a directory for exported query/mutation/action functions.
 * Uses regex-based parsing (no TypeScript compiler dependency).
 */
export async function scanFunctions(functionsDir: string): Promise<ScannedFunction[]> {
  const functions: ScannedFunction[] = []

  if (!existsSync(functionsDir)) return functions

  const files = await readdir(functionsDir)
  const tsFiles = files.filter((f) => f.endsWith(".ts") && !f.endsWith(".d.ts") && f !== "schema.ts")

  for (const file of tsFiles) {
    const filePath = join(functionsDir, file)
    const content = await readFile(filePath, "utf-8")
    const moduleName = basename(file, extname(file))

    // Match export const name = query(...), mutation(...), action(...)
    const exportRegex = /export\s+const\s+(\w+)\s*=\s*(query|mutation|action)\s*[(<]/g
    let match: RegExpExecArray | null

    while ((match = exportRegex.exec(content)) !== null) {
      const [, exportName, fnType] = match
      functions.push({
        name: `${moduleName}.${exportName}`,
        module: moduleName,
        type: fnType as "query" | "mutation" | "action",
        exportName,
      })
    }
  }

  return functions
}

/**
 * Group scanned functions by module.
 */
export function groupByModule(functions: ScannedFunction[]): Map<string, ScannedFunction[]> {
  const groups = new Map<string, ScannedFunction[]>()

  for (const fn of functions) {
    if (!groups.has(fn.module)) groups.set(fn.module, [])
    groups.get(fn.module)!.push(fn)
  }

  return groups
}

/**
 * Generate the _generated/api.ts file content.
 */
export function generateApiModule(functions: ScannedFunction[]): string {
  const lines: string[] = []
  const modules = groupByModule(functions)

  lines.push("/* eslint-disable */")
  lines.push("/* Auto-generated by ReactiveBase. Do not edit. */")
  lines.push("")
  lines.push("export interface FunctionReference<_TArgs = unknown, _TReturn = unknown> {")
  lines.push("  readonly _name: string")
  lines.push('  readonly _type: "query" | "mutation" | "action"')
  lines.push("  /** Phantom type for args inference */")
  lines.push("  readonly _args: _TArgs")
  lines.push("  /** Phantom type for return inference */")
  lines.push("  readonly _return: _TReturn")
  lines.push("}")
  lines.push("")
  lines.push("function ref<TArgs = unknown, TReturn = unknown>(")
  lines.push('  name: string, type: "query" | "mutation" | "action"')
  lines.push("): FunctionReference<TArgs, TReturn> {")
  lines.push("  return { _name: name, _type: type } as FunctionReference<TArgs, TReturn>")
  lines.push("}")
  lines.push("")
  lines.push("/** Extract args type from a function reference */")
  lines.push("export type InferArgs<T> = T extends FunctionReference<infer A, unknown> ? A : unknown")
  lines.push("/** Extract return type from a function reference */")
  lines.push("export type InferReturn<T> = T extends FunctionReference<unknown, infer R> ? R : unknown")
  lines.push("")

  // Generate api object
  lines.push("export const api = {")
  for (const [moduleName, fns] of modules) {
    lines.push(`  ${moduleName}: {`)
    for (const fn of fns) {
      lines.push(`    ${fn.exportName}: ref("${fn.name}", "${fn.type}"),`)
    }
    lines.push("  },")
  }
  lines.push("} as const")
  lines.push("")

  // Generate type-only exports for each module
  lines.push("export type ApiType = typeof api")
  lines.push("")

  return lines.join("\n")
}

/**
 * Generate the _generated/server.ts file for server-side function registration.
 */
export function generateServerModule(functions: ScannedFunction[], functionsDir: string, outputDir: string): string {
  const lines: string[] = []
  const modules = groupByModule(functions)

  lines.push("/* eslint-disable */")
  lines.push("/* Auto-generated by ReactiveBase. Do not edit. */")
  lines.push("")

  // Import all function modules
  for (const [moduleName] of modules) {
    const relPath = relative(outputDir, join(functionsDir, moduleName)).replace(/\\/g, "/")
    lines.push(`import * as ${moduleName} from "${relPath}.js"`)
  }

  lines.push("")
  lines.push("export const functions = {")

  for (const [moduleName, fns] of modules) {
    for (const fn of fns) {
      lines.push(`  "${fn.name}": ${moduleName}.${fn.exportName},`)
    }
  }

  lines.push("}")
  lines.push("")

  return lines.join("\n")
}

/**
 * Generate the _generated/dataModel.ts file with table types from schema.
 */
export function generateDataModel(_schemaSource: string): string {
  const lines: string[] = []

  lines.push("/* eslint-disable */")
  lines.push("/* Auto-generated by ReactiveBase. Do not edit. */")
  lines.push("")
  lines.push("// Re-export schema for type inference")
  lines.push('export { default as schema } from "../schema.js"')
  lines.push("")

  return lines.join("\n")
}

/**
 * Run full code generation: scan functions dir and write generated files.
 */
export async function generate(options: { functionsDir: string; outputDir: string }): Promise<GenerateResult> {
  const { functionsDir, outputDir } = options

  await mkdir(outputDir, { recursive: true })

  // Scan functions
  const functions = await scanFunctions(functionsDir)

  // Generate api.ts
  const apiContent = generateApiModule(functions)
  await writeFile(join(outputDir, "api.ts"), apiContent, "utf-8")

  // Generate server.ts
  const serverContent = generateServerModule(functions, functionsDir, outputDir)
  await writeFile(join(outputDir, "server.ts"), serverContent, "utf-8")

  // Generate dataModel.ts if schema exists
  const schemaPath = join(functionsDir, "schema.ts")
  if (existsSync(schemaPath)) {
    const schemaSource = await readFile(schemaPath, "utf-8")
    const dataModelContent = generateDataModel(schemaSource)
    await writeFile(join(outputDir, "dataModel.ts"), dataModelContent, "utf-8")
  }

  return {
    functionsFound: functions.length,
    filesGenerated: existsSync(schemaPath) ? 3 : 2,
    functions,
  }
}

export interface GenerateResult {
  functionsFound: number
  filesGenerated: number
  functions: ScannedFunction[]
}
