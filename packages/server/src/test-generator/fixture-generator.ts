/**
 * Portable Test Fixtures Generator for ReactiveBase.
 *
 * Extends test-generator/ to generate:
 *   - Type-safe factory functions (createUser(), createTask())
 *   - Relationship-aware seeding (auto-creates parent records)
 *   - Faker-based realistic data generation
 *   - Snapshot-based regression testing
 *   - Run via 'reactivebase generate:fixtures'
 *
 * Usage:
 *   const generator = new FixtureGenerator(analysis)
 *   const files = generator.generateFactories()
 *   const fixtures = generator.generateFixtures({ count: 10 })
 */

import type { SchemaAnalysis, AnalyzedTable, AnalyzedColumn } from "./test-generator.js"

// ─── Types ───────────────────────────────────────────────────────────────────

export interface FixtureGeneratorOptions {
  /** Output directory for generated files (default: "__fixtures__") */
  outputDir?: string
  /** Import path for testing utilities (default: "@reactivebase/testing") */
  importPath?: string
  /** Include faker-based realistic data (default: true) */
  useFaker?: boolean
  /** Include snapshot regression tests (default: true) */
  includeSnapshots?: boolean
  /** Default number of records per factory (default: 1) */
  defaultCount?: number
}

export interface GeneratedFactory {
  path: string
  content: string
  tableName: string
  factoryName: string
  dependencies: string[]
}

export interface GeneratedFixtureFile {
  path: string
  content: string
  tableName: string
  recordCount: number
}

export interface GeneratedSnapshotTest {
  path: string
  content: string
  tableName: string
  testCount: number
}

export interface FixtureRecord {
  table: string
  data: Record<string, unknown>
  dependencies: FixtureRecord[]
}

// ─── Default Configuration ───────────────────────────────────────────────────

const DEFAULT_OPTIONS: Required<FixtureGeneratorOptions> = {
  outputDir: "__fixtures__",
  importPath: "@reactivebase/testing",
  useFaker: true,
  includeSnapshots: true,
  defaultCount: 1,
}

// ─── Fixture Generator ──────────────────────────────────────────────────────

export class FixtureGenerator {
  private analysis: SchemaAnalysis
  private options: Required<FixtureGeneratorOptions>

  constructor(analysis: SchemaAnalysis, options: FixtureGeneratorOptions = {}) {
    this.analysis = analysis
    this.options = { ...DEFAULT_OPTIONS, ...options }
  }

  /**
   * Generate type-safe factory functions for all tables.
   */
  generateFactories(): GeneratedFactory[] {
    const factories: GeneratedFactory[] = []
    const sortedTables = this.topologicalSort(this.analysis.tables)

    for (const table of sortedTables) {
      const factoryName = `create${capitalize(table.name)}`
      const deps = table.foreignKeys.map((fk) => fk.referencedTable)
      const content = this.generateFactoryFile(table, deps)

      factories.push({
        path: `${this.options.outputDir}/factories/${table.name}.ts`,
        content,
        tableName: table.name,
        factoryName,
        dependencies: deps,
      })
    }

    // Generate index file
    const indexContent = this.generateFactoryIndex(factories)
    factories.push({
      path: `${this.options.outputDir}/factories/index.ts`,
      content: indexContent,
      tableName: "_index",
      factoryName: "_index",
      dependencies: [],
    })

    return factories
  }

  /**
   * Generate fixture data files with realistic data.
   */
  generateFixtures(options?: { count?: number }): GeneratedFixtureFile[] {
    const count = options?.count ?? this.options.defaultCount
    const files: GeneratedFixtureFile[] = []
    const sortedTables = this.topologicalSort(this.analysis.tables)

    for (const table of sortedTables) {
      const records: Record<string, unknown>[] = []
      for (let i = 0; i < count; i++) {
        records.push(this.generateRecord(table, i))
      }

      const content = `/**
 * Fixture data for ${table.name}
 * Generated by ReactiveBase fixture generator
 */

export const ${table.name}Fixtures = ${JSON.stringify(records, null, 2)} as const

export type ${capitalize(table.name)}Fixture = (typeof ${table.name}Fixtures)[number]
`

      files.push({
        path: `${this.options.outputDir}/data/${table.name}.ts`,
        content,
        tableName: table.name,
        recordCount: count,
      })
    }

    return files
  }

  /**
   * Generate snapshot regression tests.
   */
  generateSnapshotTests(): GeneratedSnapshotTest[] {
    if (!this.options.includeSnapshots) return []

    const tests: GeneratedSnapshotTest[] = []

    for (const table of this.analysis.tables) {
      const factoryName = `create${capitalize(table.name)}`
      const content = `import { describe, it, expect } from "vitest"
import { createTestServer } from "${this.options.importPath}"
import { ${factoryName} } from "../factories/${table.name}.js"

describe("${table.name} snapshots", () => {
  it("factory output matches snapshot", () => {
    const record = ${factoryName}()
    expect(record).toMatchSnapshot()
  })

  it("factory with overrides matches snapshot", () => {
    const record = ${factoryName}({ ${getFirstEditableColumn(table)} })
    expect(record).toMatchSnapshot()
  })

  it("factory creates valid records for seeding", async () => {
    const records = Array.from({ length: 5 }, (_, i) => ${factoryName}({ _index: i }))
    expect(records).toHaveLength(5)
    // Verify uniqueness of primary keys
    const ids = records.map(r => r.${table.primaryKey[0] ?? "id"})
    expect(new Set(ids).size).toBe(5)
  })

  it("relationship-aware creation succeeds", async () => {
    const server = createTestServer()
    const record = ${factoryName}()
${table.foreignKeys.map((fk) => `    expect(record.${fk.column}).toBeDefined()`).join("\n")}
    expect(record).toBeDefined()
  })
})
`

      tests.push({
        path: `${this.options.outputDir}/snapshots/${table.name}.snapshot.test.ts`,
        content,
        tableName: table.name,
        testCount: 4,
      })
    }

    return tests
  }

  /**
   * Generate a single fixture record for a table.
   */
  generateRecord(table: AnalyzedTable, index: number = 0): Record<string, unknown> {
    const record: Record<string, unknown> = {}

    for (const col of table.columns) {
      if (col.name === "id" || table.primaryKey.includes(col.name)) {
        record[col.name] = generateId(table.name, index)
      } else if (col.referencedTable) {
        record[col.name] = generateId(col.referencedTable, 0)
      } else if (col.hasDefault && col.nullable) {
        // Skip columns with defaults that are nullable
        continue
      } else {
        record[col.name] = this.options.useFaker ? generateFakerValue(col, index) : generateSimpleValue(col.type, index)
      }
    }

    return record
  }

  /**
   * Build a relationship-aware seeding plan.
   * Creates parent records before children.
   */
  buildSeedingPlan(table: AnalyzedTable, index: number = 0): FixtureRecord[] {
    const visited = new Set<string>()
    const plan: FixtureRecord[] = []

    const buildDeps = (t: AnalyzedTable) => {
      if (visited.has(t.name)) return
      visited.add(t.name)

      for (const fk of t.foreignKeys) {
        const parentTable = this.analysis.tables.find((at) => at.name === fk.referencedTable)
        if (parentTable) {
          buildDeps(parentTable)
        }
      }

      plan.push({
        table: t.name,
        data: this.generateRecord(t, index),
        dependencies: t.foreignKeys
          .map((fk) => {
            const parent = plan.find((p) => p.table === fk.referencedTable)
            return parent
          })
          .filter((p): p is FixtureRecord => p !== undefined),
      })
    }

    buildDeps(table)
    return plan
  }

  // ─── Private ───────────────────────────────────────────────────────────

  private generateFactoryFile(table: AnalyzedTable, deps: string[]): string {
    const factoryName = `create${capitalize(table.name)}`
    const typeName = `${capitalize(table.name)}Input`

    const imports =
      deps.length > 0 ? deps.map((d) => `import { create${capitalize(d)} } from "./${d}.js"`).join("\n") + "\n\n" : ""

    const fields = table.columns
      .filter((c) => !c.hasDefault || !c.nullable)
      .map((c) => {
        const optional = c.nullable || c.hasDefault ? "?" : ""
        return `  ${c.name}${optional}: ${tsType(c.type)}`
      })
      .join("\n")

    const defaults = table.columns
      .map((c) => {
        if (c.name === "id" || table.primaryKey.includes(c.name)) {
          return `    ${c.name}: overrides?.${c.name} ?? \`${table.name}_\${counter++}_\${Date.now().toString(36)}\``
        }
        if (c.referencedTable) {
          return `    ${c.name}: overrides?.${c.name} ?? create${capitalize(c.referencedTable)}().${c.referencedColumn ?? "id"}`
        }
        const value = this.options.useFaker ? fakerExpression(c) : simpleExpression(c.type)
        return `    ${c.name}: overrides?.${c.name} ?? ${value}`
      })
      .join(",\n")

    return `/**
 * Factory function for ${table.name} records.
 * Auto-creates parent records for foreign key dependencies.
 */
${imports}export interface ${typeName} {
${fields}
}

let counter = 0

export function ${factoryName}(overrides?: Partial<${typeName}> & { _index?: number }): ${typeName} {
  if (overrides?._index !== undefined) counter = overrides._index

  return {
${defaults},
  }
}

export function ${factoryName}Many(count: number, overrides?: Partial<${typeName}>): ${typeName}[] {
  return Array.from({ length: count }, (_, i) => ${factoryName}({ ...overrides, _index: i }))
}
`
  }

  private generateFactoryIndex(factories: GeneratedFactory[]): string {
    const exports = factories
      .filter((f) => f.tableName !== "_index")
      .map(
        (f) =>
          `export { create${capitalize(f.tableName)}, create${capitalize(f.tableName)}Many } from "./${f.tableName}.js"`,
      )
      .join("\n")

    return `/**
 * Auto-generated factory index for ReactiveBase test fixtures.
 * Re-exports all table factory functions.
 */
${exports}
`
  }

  private topologicalSort(tables: AnalyzedTable[]): AnalyzedTable[] {
    const sorted: AnalyzedTable[] = []
    const visited = new Set<string>()
    const visiting = new Set<string>()

    const visit = (table: AnalyzedTable) => {
      if (visited.has(table.name)) return
      if (visiting.has(table.name)) return // Circular dep — skip

      visiting.add(table.name)

      for (const fk of table.foreignKeys) {
        const dep = tables.find((t) => t.name === fk.referencedTable)
        if (dep) visit(dep)
      }

      visiting.delete(table.name)
      visited.add(table.name)
      sorted.push(table)
    }

    for (const table of tables) {
      visit(table)
    }

    return sorted
  }
}

// ─── Helpers ─────────────────────────────────────────────────────────────────

function capitalize(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1)
}

function generateId(table: string, index: number): string {
  return `${table}_${index}_${Date.now().toString(36).slice(-4)}`
}

function generateSimpleValue(type: string, index: number = 0): unknown {
  switch (type.toLowerCase()) {
    case "text":
    case "string":
    case "varchar":
      return `test_value_${index}`
    case "integer":
    case "int":
    case "number":
      return 42 + index
    case "boolean":
      return index % 2 === 0
    case "timestamp":
    case "timestamptz":
    case "date":
      return new Date(Date.now() - index * 86400000).toISOString()
    case "uuid":
      return `00000000-0000-0000-0000-${String(index + 1).padStart(12, "0")}`
    case "json":
    case "jsonb":
      return { key: `value_${index}` }
    default:
      return `test_${index}`
  }
}

function generateFakerValue(col: AnalyzedColumn, index: number = 0): unknown {
  const name = col.name.toLowerCase()
  const type = col.type.toLowerCase()

  // Infer from column name
  if (name === "email" || name.endsWith("_email")) return `user${index}@example.com`
  if (name === "name" || name === "full_name" || name === "fullname") return `Test User ${index}`
  if (name === "first_name" || name === "firstname") return `First${index}`
  if (name === "last_name" || name === "lastname") return `Last${index}`
  if (name === "username") return `user_${index}`
  if (name === "phone" || name.endsWith("_phone")) return `+1555000${String(index).padStart(4, "0")}`
  if (name === "url" || name.endsWith("_url")) return `https://example.com/${index}`
  if (name === "avatar" || name === "image" || name === "photo")
    return `https://placeholders.dev/api/64x64?text=${index}`
  if (name === "title") return `Test Title ${index}`
  if (name === "description" || name === "body" || name === "content")
    return `Test description for item ${index}. This is sample content.`
  if (name === "slug") return `test-slug-${index}`
  if (name === "status") return "active"
  if (name === "role") return "user"
  if (name === "priority") return index % 3
  if (name === "color")
    return `#${String(index * 111111)
      .padStart(6, "0")
      .slice(0, 6)}`
  if (name === "amount" || name === "price") return 1000 + index * 100
  if (name === "count" || name === "quantity") return index + 1
  if (name === "is_active" || name === "active" || name === "enabled") return true
  if (name === "is_deleted" || name === "deleted") return false

  // Fall back to type-based generation
  return generateSimpleValue(type, index)
}

function tsType(dbType: string): string {
  switch (dbType.toLowerCase()) {
    case "text":
    case "varchar":
    case "string":
    case "uuid":
      return "string"
    case "integer":
    case "int":
    case "number":
    case "bigint":
    case "real":
    case "double precision":
      return "number"
    case "boolean":
      return "boolean"
    case "json":
    case "jsonb":
      return "Record<string, unknown>"
    case "timestamp":
    case "timestamptz":
    case "date":
      return "string"
    default:
      return "unknown"
  }
}

function simpleExpression(type: string): string {
  switch (type.toLowerCase()) {
    case "text":
    case "varchar":
    case "string":
      return "`test_${counter}`"
    case "integer":
    case "int":
    case "number":
      return "counter"
    case "boolean":
      return "true"
    case "timestamp":
    case "timestamptz":
    case "date":
      return "new Date().toISOString()"
    case "uuid":
      return '`00000000-0000-0000-0000-${String(counter).padStart(12, "0")}`'
    case "json":
    case "jsonb":
      return "{ key: `value_${counter}` }"
    default:
      return "`test_${counter}`"
  }
}

function fakerExpression(col: AnalyzedColumn): string {
  const name = col.name.toLowerCase()

  if (name === "email" || name.endsWith("_email")) return "`user${counter}@example.com`"
  if (name === "name" || name === "full_name") return "`Test User ${counter}`"
  if (name === "first_name") return "`First${counter}`"
  if (name === "last_name") return "`Last${counter}`"
  if (name === "username") return "`user_${counter}`"
  if (name === "title") return "`Test Title ${counter}`"
  if (name === "description" || name === "body") return "`Description for item ${counter}`"
  if (name === "slug") return "`test-slug-${counter}`"
  if (name === "status") return '"active"'
  if (name === "role") return '"user"'
  if (name === "url" || name.endsWith("_url")) return "`https://example.com/${counter}`"
  if (name === "phone") return '`+1555${String(counter).padStart(7, "0")}`'

  return simpleExpression(col.type)
}

function getFirstEditableColumn(table: AnalyzedTable): string {
  const col = table.columns.find((c) => c.name !== "id" && !table.primaryKey.includes(c.name) && !c.referencedTable)
  if (!col) return ""
  const value =
    col.type === "text" || col.type === "varchar" || col.type === "string"
      ? '"custom_value"'
      : col.type === "integer" || col.type === "number"
        ? "99"
        : "true"
  return `${col.name}: ${value}`
}
